import { toBahtText } from '../../../services/thaiTax/bahtText';

describe('toBahtText', () => {
  it.each([
    [0, 'ศูนย์บาทถ้วน'],
    [1, 'หนึ่งบาทถ้วน'],
    [10, 'สิบบาทถ้วน'],
    [11, 'สิบเอ็ดบาทถ้วน'],
    [20, 'ยี่สิบบาทถ้วน'],
    [21, 'ยี่สิบเอ็ดบาทถ้วน'],
    [101, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    [1_000_000, 'หนึ่งล้านบาทถ้วน'],
    [1_000_001, 'หนึ่งล้านเอ็ดบาทถ้วน'],
    [11_000_000, 'สิบเอ็ดล้านบาทถ้วน'],
    [21_000_000, 'ยี่สิบเอ็ดล้านบาทถ้วน'],
    [101_000_000, 'หนึ่งร้อยเอ็ดล้านบาทถ้วน'],
    [11_000_011, 'สิบเอ็ดล้านสิบเอ็ดบาทถ้วน'],
    [1_215_750.5, 'หนึ่งล้านสองแสนหนึ่งหมื่นห้าพันเจ็ดร้อยห้าสิบบาทห้าสิบสตางค์'],
  ])('%p -> %s', (amount, expected) => {
    expect(toBahtText(amount)).toBe(expected);
  });

  it('spells out satang', () => {
    expect(toBahtText(100.25)).toBe('หนึ่งร้อยบาทยี่สิบห้าสตางค์');
    expect(toBahtText(0.01)).toBe('ศูนย์บาทหนึ่งสตางค์');
    expect(toBahtText(0.21)).toBe('ศูนย์บาทยี่สิบเอ็ดสตางค์');
  });

  it('rounds to the nearest satang', () => {
    expect(toBahtText(1.005 + 0.0001)).toBe('หนึ่งบาทหนึ่งสตางค์');
  });

  it('prefixes negatives with ลบ', () => {
    expect(toBahtText(-5)).toBe('ลบห้าบาทถ้วน');
  });
});
